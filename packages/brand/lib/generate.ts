export const STORYBOARD_PATH =
  "apps/mobile/ios/Runner/Base.lproj/LaunchScreen.storyboard";

/**
 * Patches the storyboard surgically rather than regenerating it.
 *
 * `flutter_native_splash` would rewrite this file from its own template and
 * destroy the custom two-label, full-bleed-texture layout - so the engine
 * edits exactly four things: the two label strings, and the `<namedColor>` RGB
 * blocks. Those colour blocks are a cache Xcode keeps in sync with the
 * `.colorset` files; edit only the colorset and Interface Builder will show you
 * the old colour forever.
 */
export const patchStoryboard = (xml: string, brand: Brand): string => {
  let out = xml
    .replace(
      /(<label[^>]*id="Ste-la-bl1"[^>]*)/,
      (match) => match.replace(/text="[^"]*"/, `text="${escapeXml(brand.copy.splashTitle)}"`)
    )
    .replace(
      /(<label[^>]*id="Fpv-la-bl2"[^>]*)/,
      (match) =>
        match.replace(/text="[^"]*"/, `text="${escapeXml(brand.copy.splashSubtitle)}"`)
    );

  const namedColor = (name: string, hex: Hex): void => {
    const { r, g, b, a } = hexToRgba(hex);
    const pattern = new RegExp(
      `(<namedColor name="${name}">\\s*)<color[^/]*/>`,
      "m"
    );
    out = out.replace(
      pattern,
      `$1<color red="${srgbComponent(r)}" green="${srgbComponent(g)}" blue="${srgbComponent(b)}" alpha="${(a / 255).toFixed(3)}" colorSpace="custom" customColorSpace="sRGB"/>`
    );
  };

  namedColor("LaunchForeground", brand.theme.launchForegroundLight);
  namedColor("LaunchBackground", brand.theme.launchBackgroundLight);

  return out;
};
