const srgbComponent = (value: number): string => (value / 255).toFixed(3);

/**
 * An `.colorset` Contents.json with a light entry and a dark-appearance entry,
 * matching the structure Xcode writes.
 */
export const buildColorsetJson = (light: Hex, dark: Hex): string => {
  const entry = (hex: Hex, darkAppearance: boolean): Record<string, unknown> => {
    const { r, g, b, a } = hexToRgba(hex);
    return {
      ...(darkAppearance
        ? { appearances: [{ appearance: "luminosity", value: "dark" }] }
        : {}),
      color: {
        "color-space": "srgb",
        components: {
          alpha: (a / 255).toFixed(3),
          blue: srgbComponent(b),
          green: srgbComponent(g),
          red: srgbComponent(r),
        },
      },
      idiom: "universal",
    };
  };

  return `${JSON.stringify(
    {
      colors: [entry(light, false), entry(dark, true)],
      info: { version: 1, author: "xcode" },
    },
    null,
    2
  )}\n`;
};

