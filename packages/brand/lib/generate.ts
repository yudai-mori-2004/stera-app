export const STRINGS_XML_PATH =
  "apps/mobile/android/app/src/main/res/values/strings.xml";

/**
 * Rewrites only the two brand strings, leaving `default_web_client_id` alone -
 * that value belongs to `apps/mobile/tool/sync_google_client_ids.dart`, which
 * derives it from `.env`. Two tools writing one file is how you get a merge
 * conflict in a generated artefact.
 */
export const patchStringsXml = (xml: string, brand: Brand): string =>
  xml
    .replace(
      /<string name="app_name">[^<]*<\/string>/,
      `<string name="app_name">${escapeXml(brand.copy.appName)}</string>`
    )
    .replace(
      /<string name="app_name_short">[^<]*<\/string>/,
      `<string name="app_name_short">${escapeXml(brand.copy.appNameShort)}</string>`
    );

const escapeXml = (value: string): string =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

export const INFO_PLIST_PATH = "apps/mobile/ios/Runner/Info.plist";

const PLIST_USAGE_KEYS: ReadonlyArray<[string, keyof Brand["copy"]["iosUsageDescriptions"]]> = [
  ["NSCameraUsageDescription", "camera"],
  ["NSMotionUsageDescription", "motion"],
  ["NSPhotoLibraryUsageDescription", "photoLibrary"],
  ["NSPhotoLibraryAddUsageDescription", "photoLibraryAdd"],
  ["NSMicrophoneUsageDescription", "microphone"],
  ["NSSpeechRecognitionUsageDescription", "speechRecognition"],
];

/**
 * Sets the display names and the six permission prompts.
 *
 * The permission strings are what the OS shows the user at the moment it asks
 * for the camera or their photo library, and they name the company. A token
 * rename would turn "FPV Labs uses your camera" into the fork's legal entity,
 * which reads oddly; taking them from `copy.iosUsageDescriptions` lets a fork
 * write its own, and defaults to a sentence built from the app name.
 */
export const patchInfoPlist = (plist: string, brand: Brand): string => {
  let out = plist
    .replace(
      /(<key>CFBundleDisplayName<\/key>\s*<string>)[^<]*(<\/string>)/,
      `$1${escapeXml(brand.copy.appName)}$2`
    )
    .replace(
      /(<key>CFBundleName<\/key>\s*<string>)[^<]*(<\/string>)/,
      `$1${escapeXml(brand.copy.appNameShort)}$2`
    );

  for (const [key, field] of PLIST_USAGE_KEYS) {
    const pattern = new RegExp(`(<key>${key}</key>\\s*<string>)[\\s\\S]*?(</string>)`);
    out = out.replace(
      pattern,
      `$1${escapeXml(brand.copy.iosUsageDescriptions[field])}$2`
    );
  }

  return out;
};

