/** `xl3Plus` -> `Xl3Plus`, for the generated constant names. */
const stepSuffix = (step: string): string =>
  step.charAt(0).toUpperCase() + step.slice(1);

/**
 * Flutter's `height` is a multiple of the font size, but a design system states
 * line height in pixels and so does every reference's CSS. The division is
 * emitted rather than evaluated so the generated file still reads as the
 * designed pair - `20 / 14` says "20px on a 14px face" where `1.4285714` says
 * nothing and drifts on the next edit.
 */
const lineHeightExpr = (size: number, lineHeight: number): string =>
  `${lineHeight} / ${size}`;

export const buildBrandTypeDart = (brand: Brand): string => {
  const { style, scale, weights } = brand.theme.type;

  const steps = TYPE_STEPS.map((step) => {
    const { size, lineHeight } = scale[step];
    return `  /// ${size}px on ${lineHeight}px.
  static const double size${stepSuffix(step)} = ${size};
  static const double height${stepSuffix(step)} = ${lineHeightExpr(size, lineHeight)};`;
  }).join("\n\n");

  return `${GENERATED_HEADER}

import "package:flutter/painting.dart";

/// The typographic scale.
///
/// Style: \`${style}\`. Change it in packages/brand/brand.json under
/// \`theme.type\`, override an individual step under \`theme.type.scale\`, or
/// move the weights under \`theme.type.weights\`.
///
/// \`app_text_theme.dart\` is built entirely from these, so the ramp is part of
/// the brand rather than forty literal \`fontSize:\`s. Two apps in the same
/// typeface still read as different products when this table differs, which is
/// why changing \`fonts.body\` alone never made a fork look like its own thing.
///
/// Reach for these through \`AppType\` or \`context.textTheme\` rather than
/// importing this file.
class BrandType {
  const BrandType._();

${steps}

  /// Body copy.
  static const FontWeight weightRegular = FontWeight.w${weights.regular};

  /// Emphasised body, secondary labels.
  static const FontWeight weightMedium = FontWeight.w${weights.medium};

  /// Headings and interactive labels.
  static const FontWeight weightSemibold = FontWeight.w${weights.semibold};

  /// Page titles and the display sizes.
  static const FontWeight weightBold = FontWeight.w${weights.bold};
}
`;
};

