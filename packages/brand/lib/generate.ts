// call sites are typed against them and must keep compiling whether or not a
// given fork sets the value. Dart only sees this file's initialisers, so it
// reads a populated one as a needlessly nullable declaration.
// ignore_for_file: unnecessary_nullable_for_final_variable_declarations

/// Brand-specific strings and links.
///
/// Every user-visible mention of the product name, and every outbound link,
