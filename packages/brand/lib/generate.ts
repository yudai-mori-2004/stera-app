export const BRAND_PALETTE_PATH =
  "apps/mobile/lib/src/core/theme/brand_palette.dart";

export const buildBrandPaletteDart = (brand: Brand): string => {
  const { theme } = brand;

  const groups = TOKEN_GROUPS.map((group) => {
    const body = group.tokens
      .map((token) => {
        const pair = theme.palette[token];
        if (pair === undefined) {
          return "";
        }
        const source = theme.overrides[token] !== undefined ? " (overridden)" : "";
        return [
          `  /// \`C.${token}\`${source}`,
          `  static const Color ${token}Light = ${dartColor(pair.light)};`,
          `  static const Color ${token}Dark = ${dartColor(pair.dark)};`,
        ].join("\n");
      })
      .filter((entry) => entry.length > 0)
      .join("\n\n");

    return `  // --- ${group.title} ${"-".repeat(Math.max(1, 66 - group.title.length))}\n\n${body}`;
  }).join("\n\n");

  const tintNote =
    theme.tint === 0
      ? "No tint: the neutral tokens are upstream's, unchanged."
      : `Tinted at ${theme.tint} - the neutrals carry up to ${Math.round(theme.tint * MAX_TINT * 100)}% of the accent.`;

  return `${GENERATED_HEADER}

import "package:flutter/material.dart";

/// Every colour token, resolved from packages/brand/brand.json.
///
/// \`colors.dart\` reads from here rather than carrying literals, which is what
/// makes the palette reachable from a config file at all. Values come from the
/// accent, then the tint, then \`theme.overrides\` - each stage able to overrule
/// the one before it.
///
/// ${tintNote}
class BrandPalette {
  const BrandPalette._();

${groups}

  // --- Aliases ${"-".repeat(56)}

  /// Kept so that a tree rebranded by an earlier version of the engine - where
  /// \`colors.dart\` referenced \`accentLight\` directly - still compiles.
  static const Color accentLight = brandAccentLight;
  static const Color accentDark = brandAccentDark;

  // --- Launch screen ${"-".repeat(50)}

  /// These must stay in sync with the iOS \`LaunchBackground\` /
  /// \`LaunchForeground\` colour sets, which the engine regenerates from the
  /// same values.
  static const Color launchBackgroundLight = ${dartColor(theme.launchBackgroundLight)};
  static const Color launchBackgroundDark = ${dartColor(theme.launchBackgroundDark)};
  static const Color launchForegroundLight = ${dartColor(theme.launchForegroundLight)};
  static const Color launchForegroundDark = ${dartColor(theme.launchForegroundDark)};
}
`;
};

