/**
 * Builders for the files the engine owns outright.
 *
 * Every one carries a DO-NOT-EDIT header and is rewritten wholesale on each
 * run. That is what makes runs 2..N cheap and safe: once the seams are
 * installed, a rebrand is mostly "regenerate three Dart files", not "regex
 * thirty source files again and hope".
 */

