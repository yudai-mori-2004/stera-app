export const GENERATED_HEADER = [
  "// GENERATED BY packages/brand/apply.ts - DO NOT EDIT.",
  "// Edit packages/brand/brand.json and run `bun run brand:apply`.",
].join("\n");

const dartString = (value: string): string =>
  `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

const dartColor = (hex: Hex): string => `Color(${hex})`;

