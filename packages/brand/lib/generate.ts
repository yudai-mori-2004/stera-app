export const COLORS_DART_PATH = "apps/mobile/lib/src/core/theme/colors.dart";

/** Splits `colors.dart` at the boundary between the two factories. */
const DARK_FACTORY_MARKER = "factory C.dark()";

export interface ColorsPatch {
  text: string;
  /** Tokens rewritten, per mode. */
  rewritten: number;
  /**
   * Literals that did not match the brand the engine believes is applied -
   * i.e. somebody hand-edited `colors.dart`. Reported, not fatal.
   */
  drifted: string[];
}

/**
 * Rewrites every colour literal in `colors.dart` into a reference to the
 * generated `BrandPalette`.
 *
 * The file declares each token twice, once per factory, so the two halves are
 * patched separately - the token name alone is ambiguous (`textInversePrimary`
 * and `neutralWhite` are both `0xFFFFFFFF` in light mode), but token name plus
 * which side of `factory C.dark()` it falls on is not.
 *
 * Only `<token>: const Color(0x...)` is matched, which is why the constructor's
 * `required this.textPrimary,` parameters and the shared gradient definitions
 * are left alone. Idempotent: a second run finds `BrandPalette.textPrimaryLight`
 * where the literal used to be and matches nothing.
 */
export const patchColorsDart = (
  source: string,
  previous: Brand
): ColorsPatch => {
  const boundary = source.indexOf(DARK_FACTORY_MARKER);
  if (boundary === -1) {
    return { text: source, rewritten: 0, drifted: [] };
  }

  const drifted: string[] = [];
  let rewritten = 0;

  const patchHalf = (half: string, mode: "light" | "dark"): string => {
    const suffix = mode === "light" ? "Light" : "Dark";
    let out = half;

    for (const token of TOKEN_NAMES) {
      const pattern = new RegExp(
        `(\\b${token}:\\s*)const Color\\((0x[0-9A-Fa-f]{8})\\)`
      );
      out = out.replace(pattern, (_match, prefix: string, literal: string) => {
        rewritten += 1;
        const expected = previous.theme.palette[token]?.[mode];
        if (expected !== undefined && literal.toUpperCase() !== expected.toUpperCase()) {
          drifted.push(`${token} (${mode}): found ${literal}, expected ${expected}`);
        }
        return `${prefix}BrandPalette.${token}${suffix}`;
      });
    }

    return out;
  };

  return {
    text:
      patchHalf(source.slice(0, boundary), "light") +
      patchHalf(source.slice(boundary), "dark"),
    rewritten,
    drifted,
  };
};

